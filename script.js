function setLanguage(lang) {
  const data = translations[lang] || translations.fr;
  document.documentElement.lang = lang;
  document.documentElement.dir = "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (data[key]) element.textContent = data[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.getAttribute("data-i18n-html");
    if (data[key]) element.innerHTML = data[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.getAttribute("data-i18n-placeholder");
    if (data[key]) element.setAttribute("placeholder", data[key]);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.getAttribute("data-lang") === lang);
  });

  localStorage.setItem("sampansLanguage", lang);
}

function formatEuro(amount) {
  return amount.toFixed(2).replace(".", ",") + " €";
}

function updateCalculatedPrice() {
  const copiesInput = document.getElementById("copiesInput");
  const shippingMode = document.getElementById("shippingMode");
  const priceResult = document.getElementById("priceResult");
  const hiddenSubtotalPrice = document.getElementById("hiddenSubtotalPrice");
  const hiddenPaymentFees = document.getElementById("hiddenPaymentFees");
  const hiddenTotalPrice = document.getElementById("hiddenTotalPrice");

  if (!copiesInput || !shippingMode || !priceResult || !hiddenTotalPrice) return;

  let copies = parseInt(copiesInput.value || "1", 10);
  if (!Number.isFinite(copies) || copies < 1) copies = 1;
  copiesInput.value = copies;

  let unitPrice = 0;
  let label = shippingMode.value;

  if (shippingMode.value === "France") unitPrice = 12;
  if (shippingMode.value === "Europe") unitPrice = 18;
  if (shippingMode.value === "Reste du monde") unitPrice = 18;

  if (!unitPrice) {
    priceResult.textContent = "Choisissez le mode d’envoi.";
    if (hiddenSubtotalPrice) hiddenSubtotalPrice.value = "Non calculé";
    if (hiddenPaymentFees) hiddenPaymentFees.value = "Non calculé";
    hiddenTotalPrice.value = "Non calculé";
    return;
  }

  const subtotal = copies * unitPrice;
  const feeFixed = 0.20;
  const feeRate = 0.012;
  const total = Math.ceil(((subtotal + feeFixed) / (1 - feeRate)) * 100) / 100;
  const fees = Math.max(0, total - subtotal);

  const copiesText = copies + " exemplaire" + (copies > 1 ? "s" : "");
  const subtotalText = formatEuro(subtotal);
  const feesText = formatEuro(fees);
  const totalText = formatEuro(total);

  priceResult.innerHTML = totalText + " — " + copiesText + " — " + label
    + "<br><span class=\"price-breakdown\">Dont " + subtotalText
    + " pour journal/envoi + " + feesText
    + " de frais de paiement estimés.</span>";

  if (hiddenSubtotalPrice) hiddenSubtotalPrice.value = subtotalText;
  if (hiddenPaymentFees) hiddenPaymentFees.value = feesText;
  hiddenTotalPrice.value = totalText + " — " + copiesText + " — " + label;
}

const patienceInitialGrid = [
  "1011000100110",
  "0000100011000",
  "1101111101111",
  "1111111101101",
  "1001110100000"
];

function setCardFace(card, showFront) {
  const img = card.querySelector("img");
  const label = card.querySelector(".missing-label");
  const front = card.dataset.front;
  const back = card.dataset.back;
  const frontLabel = card.dataset.frontLabel || "recto";
  const backLabel = card.dataset.backLabel || "verso";

  if (!img) return;

  img.onerror = () => {
    card.classList.add("image-missing");
    if (label) label.innerHTML = showFront ? frontLabel.replaceAll(" — ", "<br>") : backLabel.replaceAll(" — ", "<br>");
  };

  img.onload = () => {
    card.classList.remove("image-missing");
  };

  img.src = showFront ? front : back;
  card.classList.toggle("is-front", showFront);
  card.classList.toggle("is-back", !showFront);
  card.setAttribute("aria-pressed", showFront ? "true" : "false");
  if (label) label.innerHTML = (showFront ? frontLabel : backLabel).replaceAll(" — ", "<br>");
}

function resetPatienceGrid() {
  const rows = document.querySelectorAll(".patience-row");
  rows.forEach((row, rowIndex) => {
    const cards = row.querySelectorAll(".patience-card");
    cards.forEach((card, colIndex) => {
      const showFront = patienceInitialGrid[rowIndex] && patienceInitialGrid[rowIndex][colIndex] === "1";
      setCardFace(card, showFront);
    });
  });
}
function setupPatienceGrid() {
resetPatienceGrid();
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLanguage = localStorage.getItem("sampansLanguage");
  const browserLanguage = (navigator.language || "fr").slice(0, 2);
  const initialLanguage = savedLanguage && translations[savedLanguage] ? savedLanguage : (translations[browserLanguage] ? browserLanguage : "fr");

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.getAttribute("data-lang")));
  });

  const copiesInput = document.getElementById("copiesInput");
  const shippingMode = document.getElementById("shippingMode");
  const form = document.getElementById("postalOrderForm");

  if (copiesInput) copiesInput.addEventListener("input", updateCalculatedPrice);
  if (shippingMode) shippingMode.addEventListener("change", updateCalculatedPrice);
  if (form) form.addEventListener("submit", updateCalculatedPrice);

  setLanguage(initialLanguage);
  updateCalculatedPrice();
  setupPatienceGrid();
});
